#!/usr/bin/env python3
"""Generate GestaltKeyMap.swift from the Apple Wiki MobileGestalt keys dump."""
import re, sys, html, json

src = open("/home/awesomenull/.local/share/opencode/tool-output/tool_1bccfd3870012DfLcHNO9WGwJP", encoding="utf-8").read()

rows = []
for line in src.splitlines():
    if not line.startswith("| "):
        continue
    cells = [c.strip() for c in line.strip().strip("|").split(" | ")]
    if len(cells) < 2 or cells[0] == "Key":
        # rows may use different cell splits; retry greedy split
        cells = [c.strip() for c in re.split(r"\s\|\s", line.strip().strip("|"))]
        if len(cells) < 2 or cells[0] == "Key":
            continue
    key = cells[0].strip()
    hashed = cells[1].strip().strip("`")
    if key in ("---", "---") or key.startswith("--"):
        continue
    if re.match(r"^[-\s:|]+$", key):
        continue
    if not key or not hashed or not re.match(r"^[A-Za-z0-9+/=_-]{20,30}$", hashed):
        continue
    # description = last non-ios/non-device cell
    desc = ""
    if len(cells) >= 6:
        desc = cells[5]
    else:
        for c in reversed(cells[1:]):
            if c and not re.match(r"^(iOS|iPadOS)?\s*[\d.]*\s*$", c) and not re.match(r"^<a [^>]*>", c):
                desc = c
                break
    desc = html.unescape(desc)
    # strip markdown links, keep label
    desc = re.sub(r"\[([^\]]+)\]\([^)]*\)", r"\1", desc)
    desc = re.sub(r"<[^>]+>", "", desc)
    desc = desc.replace("\\-", "-").replace("[iOS](/wiki/IOS)", "iOS") if desc else desc
    key = html.unescape(key)
    rows.append((key, hashed, desc.strip()))

# dedupe by hashed
seen = {}
for k, h, d in rows:
    if h not in seen or len(d) > len(seen[h][1]):
        seen[h] = (k, d)

def esc(s):
    return s.replace("\\", "\\\\").replace('"', '\\"')

lines_out = []
lines_out.append("//")
lines_out.append("//  GestaltKeyMap.swift — GENERATED from The Apple Wiki")
lines_out.append("//  (https://theapplewiki.com/wiki/List_of_MobileGestalt_keys),")
lines_out.append("//  generated by tools/gen_keymap.py. Do not edit by hand.")
lines_out.append("//")
lines_out.append("//  SPDX-License-Identifier: CC-BY-SA-4.0 for the map data;")
lines_out.append("//  surrounding code GPL-3.0-or-later.")
lines_out.append("//")
lines_out.append("")
lines_out.append("enum GestaltKeyMap {")
lines_out.append("    /// hashed key → plain key name")
lines_out.append("    static let names: [String: String] = [")
for h in sorted(seen):
    k, d = seen[h]
    lines_out.append(f'        "{esc(k)}": "{esc(h)}",')
lines_out.append("    ]")
lines_out.append("")
lines_out.append("    /// hashed key → human description")
lines_out.append("    static let descriptions: [String: String] = [")
for h in sorted(seen):
    k, d = seen[h]
    if d:
        lines_out.append(f'        "{esc(h)}": "{esc(d)}",')
lines_out.append("    ]")
lines_out.append("}")
lines_out.append("")

with open("/home/awesomenull/Projects/worsegestalt/Sources/WorseGestalt/GestaltKeyMap.swift", "w", encoding="utf-8") as f:
    f.write("\n".join(lines_out))

print(f"entries: {len(seen)}")
